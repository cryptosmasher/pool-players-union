const CASE_FOR_UNION = [
  '# The Case for Organising Now',
  '',
  'This paper sets out why the drafting committee believes a formal union, rather than an',
  'informal players association, is the right vehicle at this moment.',
  '',
  '## The structural problem',
  '',
  'Professional pool is one of the few elite competitive disciplines in which the athletes',
  'carry almost the entire commercial risk. Entry fees are paid up front. Travel,',
  'accommodation, and equipment come out of pocket. Prize money is concentrated at the top',
  'of the bracket, so the median competitor at a major event finishes the week out of',
  'pocket even when they play well.',
  '',
  'Meanwhile the terms of participation, the calendar, the format, the broadcast rights,',
  'and the disciplinary rules are all set by parties other than the players, and can be',
  'changed after players have already committed to travel.',
  '',
  '## Why informal representation has not worked',
  '',
  '- Ad hoc player committees dissolve when their founders stop competing.',
  '- Individual players who raise concerns are easy to isolate and are frequently punished',
  'with lost invitations rather than formal sanctions.',
  '- Without a standing legal identity, players cannot hold a contract, hold funds, or',
  'take collective action with any protection.',
  '- Verbal assurances from promoters are not enforceable and are not recorded.',
  '',
  '## What a union changes',
  '',
  '1. It creates a permanent counterparty that outlives any individual career.',
  '2. It converts private grievances into documented, aggregated evidence.',
  '3. It allows terms to be negotiated once, for everybody, instead of separately and',
  'unequally for each invited player.',
  '4. It gives players an anonymous route to speak, which is the only realistic route for',
  'anyone whose invitations depend on staying quiet.',
  '',
  '## What we are not proposing',
  '',
  'We are not proposing to run tournaments, to replace existing sanctioning bodies, or to',
  'stop anyone from competing where they choose. We are not proposing a strike. We are',
  'proposing a charter, a membership, and a seat at the table.',
  '',
  '## What we need from you',
  '',
  'Read the charter. Comment on the parts you think are wrong, weak, or missing. The',
  'drafting committee will publish a revised version with a change note for every round of',
  'comments, and every prior version stays readable on this site.'
].join('\n');

