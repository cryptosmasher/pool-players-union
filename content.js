  '- A minimum rest period between matches, and a cap on matches per day per player.',
  '- No unannounced format change after the draw is published.',
  '',
  '## 3. Treatment of players',
  '',
  '- Written terms for any appearance fee, expense contribution, or media obligation.',
  '- Media and image rights limited to the promotion of that event and the archive of that',
